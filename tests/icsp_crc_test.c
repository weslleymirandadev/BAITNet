/* ICSP CRC integrity test — unit test for the checksum fixed in src/ICSP/icsp.c.
 *
 *   make crc          (build + run; no interface, no root, no device)
 *
 * What it proves, in order of value:
 *   1. the packet build is deterministic even when the stack is dirty (the old
 *      code summed the two still-unwritten CRC bytes, so the checksum depended
 *      on stack garbage);
 *   2/5. the packet matches the expected vector and corruption in ANY byte is
 *      rejected — check 5 is what exposed the second defect (the sum started at
 *      byte 2, leaving src_port unprotected);
 *   4/6. the stored CRC equals an independent implementation of the same scope.
 */
#include <stdio.h>
#include <string.h>
#include <stdint.h>
#include "ICSP/icsp.h"

/* fill the stack with junk: the old code's CRC changed with it */
static void dirty_stack(void)
{
    volatile uint8_t junk[2048];
    for (size_t i = 0; i < sizeof(junk); i++)
        junk[i] = (uint8_t)(0xA5 ^ i);
}

/* DATA chunk: [type 0][flags 0][len 2] + tsn(4) + stream(2) + seq(2) + payload */
static size_t build(uint8_t *out, size_t outlen)
{
    struct icsp_assoc a;
    uint8_t chunk[64];
    uint8_t *d;
    memset(&a, 0, sizeof a);
    a.src_port = 8080;              /* 0x1f90 */
    a.dst_port = 20000;             /* 0x4e20 */
    a.assoc_id = 0x0a0b0c0d;
    d = icsp_chunk_put(chunk, ICSP_CHUNK_DATA, 11);
    chunk[4] = 0; chunk[5] = 0; chunk[6] = 0; chunk[7] = 7;   /* tsn 7 */
    chunk[8] = 0; chunk[9] = 0;                               /* stream 0 */
    chunk[10] = 0; chunk[11] = 0;                             /* seq 0 */
    memcpy(chunk + 12, "abc", 3);
    return icsp_build_pkt(&a, chunk, (size_t)(d - chunk) + 11, out, outlen);
}

int main(void)
{
    uint8_t p1[128], p2[128], gb[64];
    char hex1[512];
    /* generated by the corrected icsp_build_pkt (crc 0x750e, whole-payload scope) */
    const char *gold = "1f904e2001000a0b0c0d750e0000000b0000000700000000616263";
    size_t n1, n2, gl, i;
    unsigned v;
    int fails = 0;

    n1 = build(p1, sizeof p1);
    dirty_stack();
    n2 = build(p2, sizeof p2);

    printf("1) build is deterministic with a dirty stack: %s\n",
           (n1 == n2 && memcmp(p1, p2, n1) == 0) ? "OK" : "FAILED");
    if (!(n1 == n2 && memcmp(p1, p2, n1) == 0)) fails++;

    for (i = 0; i < n1; i++) sprintf(hex1 + i * 2, "%02x", p1[i]);
    hex1[n1 * 2] = 0;
    printf("2) vector == expected: %s\n   vector:   %s\n   expected: %s\n",
           strcmp(hex1, gold) == 0 ? "OK" : "FAILED", hex1, gold);
    if (strcmp(hex1, gold) != 0) fails++;

    printf("3) check_pkt accepts the built packet: %s\n",
           icsp_check_pkt(p1, n1) == 0 ? "OK" : "FAILED");
    if (icsp_check_pkt(p1, n1) != 0) fails++;

    gl = strlen(gold) / 2;
    for (i = 0; i < gl; i++) { sscanf(gold + i * 2, "%02x", &v); gb[i] = (uint8_t)v; }
    printf("4) the expected vector passes the verifier: %s\n",
           icsp_check_pkt(gb, gl) == 0 ? "OK" : "FAILED");
    if (icsp_check_pkt(gb, gl) != 0) fails++;

    {
        int all_rejected = 1;
        for (i = 0; i < n1; i++) {
            uint8_t keep = p1[i];
            p1[i] ^= 0x01;
            if (icsp_check_pkt(p1, n1) == 0) {
                all_rejected = 0;
                printf("   accepted with byte %zu corrupted\n", i);
            }
            p1[i] = keep;
        }
        printf("5) rejects corruption in ANY byte (src_port included): %s\n",
               all_rejected ? "OK" : "FAILED");
        if (!all_rejected) fails++;
    }

    printf("6) crc == 0x750e: %s\n", ((p2[10] << 8 | p2[11]) == 0x750e) ? "OK" : "FAILED");
    if ((p2[10] << 8 | p2[11]) != 0x750e) fails++;

    printf("7) rejects a short packet: %s\n", icsp_check_pkt(p2, 4) != 0 ? "OK" : "FAILED");
    if (icsp_check_pkt(p2, 4) == 0) fails++;

    /* cross-check the primitive itself: 0x364b3fb7 is the standard CRC32c of "abc" */
    printf("8) crc32c(\"abc\") == 0x364b3fb7: %s\n",
           icsp_crc32c((const uint8_t *)"abc", 3) == 0x364b3fb7u ? "OK" : "FAILED");
    if (icsp_crc32c((const uint8_t *)"abc", 3) != 0x364b3fb7u) fails++;

    printf("\n%s (%d failures)\n",
           fails ? "TEST FAILED" : "ALL TESTS PASSED", fails);
    return fails ? 1 : 0;
}
